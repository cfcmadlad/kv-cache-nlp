import argparse
import sys
from pathlib import Path

import numpy as np
import torch

sys.path.insert(0, str(Path(__file__).resolve().parent))
from cache_demo import load_pair
from data_utils import REPO_ROOT, read_jsonl_texts
from kvc.cache import Policy, patch_entropy_scores, patch_scores, visible_mask
from kvc.patching import entropy_from_logits, patch_flags
from models.entropy import BOS
from train_blt import patch_settings

POLICIES = ("full", "recency", "random", "entropy", "entropy_inv")


@torch.no_grad()
def next_byte(model, entropy, cfg: dict, seq: list, mode: str, budget: int, sink: int, recent: int, device: str) -> int:
    ps = patch_settings(cfg)
    ids = torch.tensor([[BOS, *seq]], device=device)
    n = ids.size(1)
    h = entropy_from_logits(entropy(ids)[0][0]).cpu().numpy().astype(np.float32)
    flags = patch_flags(h, np.arange(n), np.zeros(n, dtype=bool), ps["mode"], ps["theta"], ps["max_len"], ps["stride"])
    inputs = (ids, torch.from_numpy(flags)[None].to(device))
    if mode != "full":
        cs = np.cumsum(flags)
        P = int(cs[-1]) + 1
        score = patch_entropy_scores(cs - flags, h.astype(np.float64), P, "mean")
        pol = Policy(mode, budget, sink, recent)
        mask = visible_mask(P, patch_scores(pol, P, score, np.random.default_rng([0, 0])), pol)
        inputs = (*inputs, torch.from_numpy(mask)[None].to(device))
    return int(model(inputs)[0][0, -1].argmax())


def text(b: list) -> str:
    return bytes(b).decode("utf-8", errors="replace").replace("\n", " ")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="results/part3/generation_divergence.md")
    ap.add_argument("--prompts", nargs="+", default=["tinystories:0:700", "tinystories:13:600", "wikitext103:0:1500", "wikitext103:1:1500"])
    ap.add_argument("--budgets", type=int, nargs=2, default=[32, 64])
    ap.add_argument("--new-bytes", type=int, default=80)
    ap.add_argument("--min-bytes", type=int, default=600)
    ap.add_argument("--sink", type=int, default=1)
    ap.add_argument("--recent", type=int, default=8)
    ap.add_argument("--tail", type=int, default=100)
    args = ap.parse_args()
    device = "cpu"
    budgets = dict(zip(("tinystories", "wikitext103"), args.budgets))
    lines = ["Greedy continuations of the same prompt with the full cache and with a patch budget under each policy, seed-0 entropy-patched BLT models from the `v0.3-part3` release, CPU. Each step recomputes the entropy patches and the eviction mask on the text so far. `diverges at` is the index of the first generated byte that differs from the full-cache continuation. Regenerate with `python scripts/generation_divergence.py`.", ""]
    loaded = {}
    for spec in args.prompts:
        name, idx, plen = spec.split(":")
        if name not in loaded:
            loaded[name] = load_pair(name, device)
        model, entropy, cfg = loaded[name]
        docs = [t.encode("utf-8") for t in read_jsonl_texts(REPO_ROOT / "data" / "processed" / name / "val.jsonl", 500) if len(t.encode("utf-8")) >= args.min_bytes]
        doc = docs[int(idx)]
        prompt = list(doc[:int(plen)])
        reference = list(doc[int(plen):int(plen) + args.new_bytes])
        lines += [f"## {name}, document {idx}, prompt of {plen} bytes, budget {budgets[name]} patches", "", f"End of the prompt: `{text(prompt[-args.tail:])}`", "", f"True continuation: `{text(reference)}`", ""]
        outs = {}
        for mode in POLICIES:
            seq = list(prompt)
            for _ in range(args.new_bytes):
                seq.append(next_byte(model, entropy, cfg, seq, mode, budgets[name], args.sink, args.recent, device))
            outs[mode] = seq[len(prompt):]
        for mode in POLICIES:
            out = outs[mode]
            same = next((i for i, (a, b) in enumerate(zip(out, outs["full"])) if a != b), None)
            match = sum(a == b for a, b in zip(out, reference))
            tag = "reference run" if mode == "full" else (f"diverges at {same}" if same is not None else "identical to full")
            lines.append(f"- {mode} ({tag}; {match} of {len(reference)} bytes equal the true continuation): `{text(out)}`")
        lines.append("")
        print(spec, flush=True)
    out = REPO_ROOT / args.out
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
