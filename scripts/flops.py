import argparse
import json
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent


def block_macs(d: int, n_kv: float) -> float:
    return 12 * d * d + 2 * n_kv * d


def block_params(d: int) -> int:
    return 12 * d * d + 9 * d


def blt_params(c: dict) -> int:
    dl, dg = c["local_dim"], c["global_dim"]
    return (257 * dl + c["enc_layers"] * block_params(dl) + dl * dg + dg + c["global_layers"] * block_params(dg) + 2 * dg
            + dg * dl + dl + c["dec_layers"] * block_params(dl) + 2 * dl + dl * 256)


def entropy_params(c: dict) -> int:
    d = c["dim"]
    return 257 * d + c["layers"] * block_params(d) + 2 * d + d * 256


def gpt_params(c: dict, positions: int) -> int:
    d = c["dim"]
    return c["vocab"] * d + positions * d + c["layers"] * (12 * d * d + 13 * d) + 2 * d


def blt_macs(c: dict, n: int, patch: float, budget: int = 0) -> float:
    dl, dg = c["local_dim"], c["global_dim"]
    entries = n / patch if not budget else min(n / patch, budget)
    local = (c["enc_layers"] + c["dec_layers"]) * block_macs(dl, min(c["local_window"], n)) + dg * dl + dl * 256
    per_patch = dl * dg + c["global_layers"] * block_macs(dg, entries)
    return local + per_patch / patch


def entropy_macs(c: dict, n: int) -> float:
    return c["layers"] * block_macs(c["dim"], min(c["window"], n)) + c["dim"] * 256


def gpt_macs(c: dict, entries: float) -> float:
    return c["layers"] * block_macs(c["dim"], entries) + c["dim"] * c["vocab"]


def fmt(macs: float) -> str:
    return f"{2 * macs / 1e6:.2f}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", default="configs/flops.json")
    ap.add_argument("--out", default="results/part3/flops.md")
    args = ap.parse_args()
    cfg = json.loads((REPO_ROOT / args.config).read_text(encoding="utf-8"))
    blt, ent, bpe, byt = cfg["blt"], cfg["entropy"], cfg["bpe"], cfg["byte_transformer"]
    patch, token, budget = cfg["bytes_per_patch"], cfg["bytes_per_token"], cfg["cache_patches"]
    counts = {"BLT": (blt_params(blt), blt["expected_params"]), "entropy model": (entropy_params(ent), ent["expected_params"]),
              "BPE transformer": (gpt_params(bpe, bpe["block"]), bpe["expected_params"])}
    for name, (got, want) in counts.items():
        if got != want:
            raise SystemExit(f"parameter count mismatch for {name}: formula {got:,}, expected {want:,}")
    byte_params = gpt_params(byt, 0)
    kv_patch = 2 * blt["global_layers"] * blt["global_dim"] * 2
    kv_gpt = lambda c: 2 * c["layers"] * c["dim"] * 2
    lines = [
        "Analytic compute per generated byte at steady state, from the formulas below. Nothing here is measured. MFLOPs are millions of floating-point operations, counting a multiply-accumulate as 2. Regenerate with `python scripts/flops.py`.", "",
        "## Formulas", "",
        "- One transformer block of width d attending to n_kv cached entries: 12 d^2 multiply-accumulates for the QKV and output projections (4 d^2) and the 4x MLP (8 d^2), plus 2 n_kv d for the query-key scores and the weighted sum of values.",
        "- BLT per byte: local encoder and decoder blocks (width local_dim, attending to min(window, context) bytes), the projection from global to local width (global_dim x local_dim) and the output layer (local_dim x 256), plus once per patch the pooling projection (local_dim x global_dim) and the global blocks (width global_dim, attending to the global cache entries), divided by the bytes per patch.",
        "- Entropy model per byte: its blocks (window 512) and output layer. It is needed for entropy patching only; fixed-stride patching does not need it.",
        "- BPE transformer per token: its blocks attending to the tokens in context, plus the output layer (width x 8,000); divided by bytes per token to give a per-byte figure.",
        "- Byte-level transformer of the same width: its blocks attending to one entry per byte, plus the output layer (width x 256).",
        "- Not counted: layer norms, softmax, GELU, rotary embeddings, embedding lookups, the scatter-add pooling, and memory traffic. Attention is counted as dense over the cached entries. The same convention is used for every model, so ratios are meaningful and absolute values are approximate.", "",
        "## Assumptions", "",
        f"- {patch} bytes per patch (measured, entropy patching) and {token} bytes per BPE token (measured on validation text: 4.1 on TinyStories, 3.9 on WikiText-103). Cache budgets keep {budget} entries; a budgeted cache never holds more entries than the context provides.",
        f"- The BPE transformer was trained with a {bpe['block']}-token context (about {int(bpe['block'] * token)} bytes); rows beyond that are marked with a dagger and are hypothetical. The BLT was trained on 4,096-byte chunks and the byte-level transformer was not trained.",
        "- Parameter counts come from the same widths and are checked against the real models: BLT "
        f"{counts['BLT'][0]:,}, entropy model {counts['entropy model'][0]:,}, BPE transformer {counts['BPE transformer'][0]:,} (all three match `num_params()` of the trained models). The byte-level transformer has {byte_params:,} parameters (no positional table, not trained).",
        f"- KV size is fp16 keys and values over all layers: {kv_patch:,} bytes per BLT global entry and {kv_gpt(byt):,} bytes per entry for a width-{byt['dim']} model with {byt['layers']} layers. The BLT's fixed byte window caches (786 KB) and the entropy model's window cache (about 2.1 MB) are not included; see `deploy_memory.md`.", ""]
    for n in cfg["contexts"]:
        dag = lambda tokens: "†" if tokens > bpe["block"] else ""
        rows = []
        for label, macs, entries, kv in [
            ("BLT 13.3M, full global cache", blt_macs(blt, n, patch), n / patch, kv_patch),
            (f"BLT, {budget}-patch cache", blt_macs(blt, n, patch, budget), min(n / patch, budget), kv_patch),
            ("BLT, full cache, plus entropy model", blt_macs(blt, n, patch) + entropy_macs(ent, n), n / patch, kv_patch),
            (f"BLT, {budget}-patch cache, plus entropy model", blt_macs(blt, n, patch, budget) + entropy_macs(ent, n), min(n / patch, budget), kv_patch),
            (f"BPE transformer 13.8M, full cache{dag(n / token)}", gpt_macs(bpe, n / token) / token, n / token, kv_gpt(bpe)),
            (f"BPE transformer, {budget}-token cache{dag(n / token)}", gpt_macs(bpe, min(n / token, budget)) / token, min(n / token, budget), kv_gpt(bpe)),
            (f"Byte-level transformer, full cache", gpt_macs(byt, n), n, kv_gpt(byt)),
            (f"Byte-level transformer, {budget}-entry cache", gpt_macs(byt, min(n, budget)), min(n, budget), kv_gpt(byt)),
            (f"Byte-level transformer, {int(budget * patch)}-entry cache (same text span as {budget} patches)", gpt_macs(byt, min(n, budget * patch)), min(n, budget * patch), kv_gpt(byt)),
        ]:
            rows.append((label, macs, entries, kv))
        base = rows[0][1]
        lines += [f"## Context of {n:,} bytes", "", "| Model | KV entries | KV cache (KB, fp16) | MFLOPs per byte | Relative to BLT with full cache |", "|---|---|---|---|---|"]
        for label, macs, entries, kv in rows:
            lines.append(f"| {label} | {entries:,.0f} | {entries * kv / 1000:,.0f} | {fmt(macs)} | {macs / base:.2f} |")
        lines.append("")
    out = REPO_ROOT / args.out
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
